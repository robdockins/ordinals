(** * Well-founded relations generate ordinals *)

Section wf_ord.
  Variable A:Type.
  Variable R:A -> A -> Prop.

  Fixpoint mk_wf_ord (a:A) (X:Acc R a) : Ord :=
    match X with
    | Acc_intro _ H => ord { a':A | R a' a } (fun x => mk_wf_ord (proj1_sig x) (H _ (proj2_sig x)))
    end.

  Hypothesis Hwf : well_founded R.
  Definition wf_ord_elt (a:A) : Ord := mk_wf_ord a (Hwf a).

  Lemma wf_ord_Acc_irrelevant: forall a H1 H2, mk_wf_ord a H1 ≤ mk_wf_ord a H2.
  Proof.
    intros a Hacc. generalize Hacc. induction Hacc.
    intros [H1] [H2]; simpl.
    rewrite ord_le_unfold; intros [a' Ha']. simpl.
    rewrite ord_lt_unfold; exists (exist _ a' Ha'); simpl.
    apply H0; auto.
  Qed.

  Lemma wf_ord_lt : forall a a', R a' a -> wf_ord_elt a' < wf_ord_elt a.
  Proof.
    unfold wf_ord_elt. intros a a'.
    generalize (Hwf a'). revert a'.
    generalize (Hwf a).
    induction a using (well_founded_induction Hwf); intros.
    destruct a0; simpl.
    rewrite ord_lt_unfold.
    exists (exist _ a' H0); simpl.
    rewrite ord_le_unfold.
    destruct a1. simpl; intros.
    destruct a2. simpl.
    apply H; auto.
  Qed.

  Lemma wf_ord_lt_trans : forall a a', clos_trans _ R a' a -> wf_ord_elt a' < wf_ord_elt a.
  Proof.
    intros; induction H.
    - apply wf_ord_lt; auto.
    - eapply ord_lt_trans; eauto.
  Qed.

  Lemma wf_ord_le_trans : forall a a', clos_refl_trans _ R a' a -> wf_ord_elt a' ≤ wf_ord_elt a.
  Proof.
    intros; induction H.
    - apply ord_lt_le; apply wf_ord_lt; auto.
    - apply ord_le_refl.
    - eapply ord_le_trans; eauto.
  Qed.

End wf_ord.

Definition wf_ord {A:Type} (R: A -> A -> Prop) (H:well_founded R) : Ord :=
  limOrd (wf_ord_elt A R H).

Lemma wf_ord_proof_irr_le: forall A (R: A -> A -> Prop) H1 H2,
  wf_ord R H1 <= wf_ord R H2.
Proof.
  unfold wf_ord. intros.
  apply limit_least. intro i.
  rewrite ord_lt_unfold. simpl. exists i.
  apply wf_ord_Acc_irrelevant.
Qed.

(* The ordinal generated by a well-founded relation depends only on the relation,
   not on the proof of well-foundedness. *)
Theorem wf_ord_proof_irr: forall A (R: A -> A -> Prop) H1 H2,
  wf_ord R H1 ≈ wf_ord R H2.
Proof.
  intros; split; apply wf_ord_proof_irr_le; auto.
Qed.

(* The ordinal generated by the strict order on natural numbers is omega. *)
Theorem wf_ord_lt_nat_omega : wf_ord lt Wf_nat.lt_wf ≈ ω.
Proof.
  split.
  - rewrite ord_le_unfold. simpl; intro i.
    rewrite ord_lt_unfold. simpl. exists i.
    unfold wf_ord_elt. generalize (Wf_nat.lt_wf i).
    induction i using (well_founded_induction Wf_nat.lt_wf); simpl.
    intros [Hacc]; simpl.
    rewrite ord_le_unfold; simpl.
    intros [j Hj]. simpl.
    rewrite H; auto.
    apply natOrdSize_increasing; auto.
  - rewrite ord_le_unfold; intro i.
    rewrite ord_lt_unfold.
    simpl. exists i.
    unfold wf_ord_elt.
    generalize (Wf_nat.lt_wf i).
    induction i; simpl; intros; auto with ord.
    apply succ_least.
    destruct a; simpl.
    rewrite ord_lt_unfold; simpl.
    exists (exist _ i (PeanoNat.Nat.lt_succ_diag_r i)); simpl.
    apply IHi.
Qed.

Fixpoint ord_transitive_closure_type (x:Ord) : Type :=
  match x with
  | ord A f => A + sigT (fun i:A => ord_transitive_closure_type (f i))
  end.

Fixpoint ord_transitive_closure_ord (x:Ord): ord_transitive_closure_type x -> Ord :=
  match x as x' return ord_transitive_closure_type x' -> Ord with
  | ord A f =>
      fun q =>
        match q with
        | inl i => f i
        | inr (existT _ i q') => ord_transitive_closure_ord (f i) q'
        end
  end.

Definition ord_transitive_closure (x:Ord): Ord :=
  ord (ord_transitive_closure_type x) (ord_transitive_closure_ord x).

Definition ord_transitive_closure_inj (x:Ord) : x -> ord_transitive_closure_type x :=
  match x as x' return x' -> ord_transitive_closure_type x' with
  | ord A f => fun i => inl i
  end.

Fixpoint transitive_closure_collapse (x:Ord) :
  forall (i:ord_transitive_closure_type x) (j: ord_transitive_closure_ord x i),
    ord_transitive_closure_type x :=

  match x as x' return
        forall (i:ord_transitive_closure_type x') (j: ord_transitive_closure_ord x' i),
          ord_transitive_closure_type x' with
  | ord A f =>
      fun i =>
        match i as i' return
              forall (j: ord_transitive_closure_ord (ord A f) i'), ord_transitive_closure_type (ord A f)
        with
        | inl i => fun j => inr (existT _ i (ord_transitive_closure_inj (f i) j))
        | inr (existT _ i q') => fun j => inr (existT _ i (transitive_closure_collapse (f i) q' j) )
        end
  end.

Lemma ord_transitive_closure_inj_correct: forall (x:Ord) (i:x),
    ord_transitive_closure_ord x (ord_transitive_closure_inj x i) ≈ i.
Proof.
  intros [A f]; simpl.
  intro; auto with ord.
Qed.

Lemma transitive_closure_collapse_correct:
  forall (x:Ord) (i:ord_transitive_closure_type x) (j: ord_transitive_closure_ord x i),
    ord_transitive_closure_ord x (transitive_closure_collapse x i j) ≈ j.
Proof.
  induction x as [A f Hind].
  intros [i|[i q]]; simpl.
  - intros; apply ord_transitive_closure_inj_correct.
  - intros. apply Hind.
Qed.

Lemma ord_transitive_closure_transitive (x:Ord):
  forall (i: ord_transitive_closure x) (j: i), exists (k: ord_transitive_closure x),
    k ≈ j.
Proof.
  simpl in *; intros.
  exists (transitive_closure_collapse x i j).
  apply transitive_closure_collapse_correct.
Qed.

Lemma ord_transitive_closure_le1: forall (x:Ord), x <= ord_transitive_closure x.
Proof.
  intros [A f]; simpl.
  rewrite ord_le_unfold. intro i. simpl.
  rewrite ord_lt_unfold; simpl.
  exists (inl i); auto with ord.
Qed.

Lemma ord_transitive_closure_le2: forall (x:Ord), ord_transitive_closure x <= x.
Proof.
  induction x as [A f Hind]; simpl.
  rewrite ord_le_unfold. intros [i|[i q]]; simpl.
  - simpl; auto with ord.
  - rewrite ord_lt_unfold; simpl.
    exists i. simpl.
    transitivity (ord_transitive_closure (f i)); simpl; auto with ord.
    apply ord_lt_le. rewrite ord_lt_unfold; simpl.
    exists q. auto with ord.
Qed.

Lemma ord_transitive_closure_eq : forall (x:Ord), ord_transitive_closure x ≈ x.
Proof.
  intros; split.
  apply ord_transitive_closure_le2.
  apply ord_transitive_closure_le1.
Qed.

Lemma ord_transitive_closure_lt (x:Ord):
  forall j,
    j < x ->
    exists k:ord_transitive_closure x, j <= k.
Proof.
  intros.
  rewrite <- (ord_transitive_closure_eq x) in H.
  rewrite ord_lt_unfold in H.
  destruct H as [i Hi].
  exists i. auto.
Qed.


Definition ord_R (x:Ord) (a:ord_transitive_closure_type x) (b:ord_transitive_closure_type x): Prop :=
  ord_transitive_closure_ord x a < ord_transitive_closure_ord x b.

Lemma ord_R_well_founded x: well_founded (ord_R x).
  intro a.
  induction a using (size_induction (ord_transitive_closure x)).
  constructor. intros y HR.
  unfold ord_R in HR.
  apply H. auto.
Qed.

Lemma ord_R_le1: forall (x:Ord),
    x <= wf_ord (ord_R x) (ord_R_well_founded x).
Proof.
  intros x.
  rewrite (ord_transitive_closure_le1) at 1.
  rewrite ord_le_unfold. simpl. intro a.
  rewrite ord_lt_unfold; simpl. exists a.
  induction a as [a Hinda] using (size_induction (ord_transitive_closure x)).
  rewrite ord_le_unfold; intro q.
  destruct (ord_transitive_closure_transitive x a q) as [k Hk].
  rewrite <- Hk.
  rewrite (Hinda k); auto with ord.
  - apply wf_ord_lt. hnf.
    rewrite Hk. auto with ord.
  - rewrite Hk. auto with ord.
Qed.

Lemma ord_R_le2: forall (x:Ord),
    wf_ord (ord_R x) (ord_R_well_founded x) <= x.
Proof.
  intros x.
  transitivity (ord_transitive_closure x); [ | apply ord_transitive_closure_eq ].
  rewrite ord_le_unfold. simpl. intro a.
  rewrite ord_lt_unfold; simpl. exists a.
  unfold wf_ord_elt.
  generalize (ord_R_well_founded x a).
  induction a as [a Hinda] using (size_induction (ord_transitive_closure x)).
  intros [Hacc]; simpl.
  rewrite ord_le_unfold; simpl.
  intros [q Hq]; simpl.
  unfold ord_R in Hq.
  rewrite Hinda; auto with ord.
Qed.

Section simulates.
  Context {A B: Type}.
  Variable R: A -> A -> Prop.
  Variable S: B -> B -> Prop.

  Definition simulation (F: A -> B -> Prop) :=
    forall (a a':A) (b:B), R a' a -> F a b -> exists b', S b' b /\ F a' b'.

  Definition total (F: A -> B -> Prop) :=
    forall (a:A), exists (b:B), F a b.

  Lemma simulation_Acc: forall F,
      simulation F ->
      forall b,
      Acc S b ->
      forall a,
        F a b ->
        Acc R a.
  Proof.
    intros F HF b Hb.
    induction Hb as [b Hacc Hind].
    intros a Hab.
    constructor; intros a' Ha'.
    destruct (HF a a' b) as [b' [Hb'1 Hb'2]]; auto.
    apply Hind with b'; auto.
  Qed.

  Definition simulates :=  exists F, simulation F /\ total F.

  Lemma simulates_wf:
    simulates ->
    well_founded S ->
    well_founded R.
  Proof.
    intros [F [HF1 HF2]] Hwf.
    intro a.
    destruct (HF2 a) as [b Hb].
    apply simulation_Acc with F b; auto.
  Qed.
End simulates.

Definition transitive_simulation
  {A B C:Type} (F: A -> B -> Prop) (G:B -> C -> Prop) : A -> C -> Prop :=
  fun a c => exists b, F a b /\ G b c.

Lemma transitive_is_simulation (A B C:Type) (F: A -> B -> Prop) (G:B -> C -> Prop)
  (R: A -> A -> Prop)
  (S: B -> B -> Prop)
  (T: C -> C -> Prop) :

  simulation R S F ->
  simulation S T G ->
  simulation R T (transitive_simulation F G).
Proof.
  intros HsimF HsimG.
  intros a a' c HR [b [HF HG]].
  destruct (HsimF a a' b HR HF) as [b' [HS HF2]].
  destruct (HsimG b b' c HS HG) as [c' [HT HG2]].
  exists c'; split; auto.
  hnf. exists b'. split; auto.
Qed.

Lemma simulates_refl (A:Type) (R:A -> A -> Prop): simulates R R.
Proof.
  exists (@eq A). split.
  - hnf. intros; subst; eauto.
  - hnf; intros. eauto.
Qed.

Lemma simulates_transitive (A B C:Type)
  (R: A -> A -> Prop)
  (S: B -> B -> Prop)
  (T: C -> C -> Prop) :
  simulates R S -> simulates S T -> simulates R T.
Proof.
  intros [F [HF1 HF2]] [G [HG1 HG2]].
  exists (transitive_simulation F G).
  split. eapply transitive_is_simulation; eauto.
  hnf; intros.
  destruct (HF2 a) as [b Hb].
  destruct (HG2 b) as [c Hc].
  exists c. exists b. split; auto.
Qed.

Lemma ord_R_simulates1: forall (x y: Ord),
    x <= y ->
    simulates (ord_R x) (ord_R y).
Proof.
  intros. red. simpl.
  exists (fun a b => ord_transitive_closure_ord x a <= ord_transitive_closure_ord y b).
  split.
  - hnf; simpl; intros.
    unfold ord_R in *.
    assert (H2: ord_transitive_closure_ord x a' < ord_transitive_closure_ord y b).
    { apply ord_lt_le_trans with (ord_transitive_closure_ord x a); auto. }
    rewrite ord_lt_unfold in H2.
    destruct H2 as [q Hq].
    destruct (ord_transitive_closure_transitive y b q) as [b' Hb'].
    exists b'; split; rewrite Hb'; auto with ord.
  - hnf; simpl; intros.
    assert (ord_transitive_closure x <= ord_transitive_closure y).
    { repeat rewrite ord_transitive_closure_eq; auto. }
    rewrite ord_le_unfold in H0.
    specialize (H0 a).
    rewrite ord_lt_unfold in H0. auto.
Qed.

Lemma ord_R_simulates2: forall (x y:Ord),
    simulates (ord_R x) (ord_R y) ->
    x <= y.
Proof.
  intros x y [F [HF1 HF2]].
  cut (ord_transitive_closure x <= ord_transitive_closure y).
  { repeat rewrite ord_transitive_closure_eq; auto. }
  hnf in HF1. unfold ord_R in HF1.
  rewrite ord_le_unfold. intro a.
  destruct (HF2 a) as [b Hb].
  rewrite ord_lt_unfold. exists b.
  clear HF2.
  revert b Hb.
  induction a as [a Hind] using size_induction.
  intros b Hb.
  rewrite ord_le_unfold; intro q.
  destruct (ord_transitive_closure_transitive x a q) as [k Hk].
  destruct (HF1 a k b) as [b' [Hb'1 Hb'2]]; auto.
  - rewrite Hk. auto with ord.
  - rewrite <- Hk.
    rewrite Hind with (b:=b'); auto with ord.
    rewrite Hk; auto with ord.
Qed.

Lemma ord_R_simulates: forall x y, x <= y <-> simulates (ord_R x) (ord_R y).
Proof.
  intuition.
  apply ord_R_simulates1; auto.
  apply ord_R_simulates2; auto.
Qed.

Lemma wf_ord_simulates1:
  forall A B
    (R:A -> A -> Prop)
    (S:B -> B -> Prop)
    (HR: well_founded R)
    (HS: well_founded S),
    simulates R S -> wf_ord R HR <= wf_ord S HS.
Proof.
  intros A B R S HR HS [F [HF1 HF2]].
  unfold wf_ord.
  rewrite ord_le_unfold; simpl; intro a.
  rewrite ord_lt_unfold; simpl.
  destruct (HF2 a) as [b Hb].
  exists b.
  unfold wf_ord_elt.
  generalize (HR a) (HS b).
  intro Hacc.
  revert b Hb.
  induction a as [a Hind] using (well_founded_induction HR).
  destruct Hacc as [Hacc]; simpl.
  intros.
  rewrite ord_le_unfold. simpl.
  intros [a' Ha']; simpl.
  destruct (HF1 a a' b) as [b' [Hb'1 Hb'2]]; auto.
  destruct a0 as [a0].
  rewrite (Hind a') with (b:=b') (a:=a0 b' Hb'1); auto.
  rewrite ord_lt_unfold; simpl.
  exists (exist _  b' Hb'1); simpl.
  auto with ord.
Qed.

Lemma wf_ord_simulates2:
  forall A B
    (R:A -> A -> Prop)
    (S:B -> B -> Prop)
    (HR: well_founded R)
    (HS: well_founded S),
    wf_ord R HR <= wf_ord S HS ->
    simulates R S.
Proof.
  intros A B R S HR HS H.
  hnf.
  exists (fun a b => exists Ha, exists Hb,
              mk_wf_ord A R a Ha <= mk_wf_ord B S b Hb).
  split.
  - hnf; simpl.
    intros a a' b Hr [[Ha] [[Hb] HF]].
    simpl in *.
    rewrite ord_le_unfold in HF. simpl in HF.
    specialize (HF (exist _ a' Hr)); simpl in HF.
    rewrite ord_lt_unfold in HF.
    destruct HF as [[b' Hs] HF]. simpl in *.
    exists b'; split; eauto.
  - hnf. intros.
    unfold wf_ord in H; simpl in H.
    rewrite ord_le_unfold in H. simpl in H.
    specialize (H a).
    rewrite ord_lt_unfold in H. simpl in H.
    destruct H as [b Hb].
    exists b.
    exists (HR a).
    exists (HS b).
    auto.
Qed.

Lemma wf_ord_simulates:
  forall A B
    (R:A -> A -> Prop)
    (S:B -> B -> Prop)
    (HR: well_founded R)
    (HS: well_founded S),
    wf_ord R HR <= wf_ord S HS <-> simulates R S.
Proof.
  intros; split.
  apply wf_ord_simulates2.
  apply wf_ord_simulates1.
Qed.

Theorem ordinal_simulations:
  (forall (x y:Ord),
      x <= y <-> simulates (ord_R x) (ord_R y)) /\
  (forall A B
    (R:A -> A -> Prop)
    (S:B -> B -> Prop)
    (HR: well_founded R)
    (HS: well_founded S),
      wf_ord R HR <= wf_ord S HS <-> simulates R S).
Proof.
  split. apply ord_R_simulates. apply wf_ord_simulates.
Qed.

Lemma ord_R_round_trip: forall (x:Ord),
    wf_ord (ord_R x) (ord_R_well_founded x) ≈ x.
Proof.
  intros; split.
  apply ord_R_le2.
  apply ord_R_le1.
Qed.

Lemma simulates_round_trip1:
  forall A (R:A -> A -> Prop) (HR: well_founded R),
    simulates R (ord_R (wf_ord R HR)).
Proof.
  intros A R HR. simpl.
  hnf. exists (fun a b => inl a = b). split.
  - hnf; simpl; intros; subst.
    exists (inl _ a'); simpl. split; auto.
    red. simpl.
    apply wf_ord_lt; auto.
  - hnf; simpl; intros.
    exists (inl a); auto.
Qed.

Lemma simulates_round_trip2:
  forall A (R: A -> A -> Prop) (HR: well_founded R),
    simulates (ord_R (wf_ord R HR)) R.
Proof.
  intros A R HR.
  hnf. simpl. unfold wf_ord_elt.

  exists (fun a b =>
            match a with
            | inl x => mk_wf_ord A R x (HR x) <= mk_wf_ord A R b (HR b)
            | inr (existT _ i q) => ord_transitive_closure_ord (mk_wf_ord A R i (HR i)) q <= mk_wf_ord A R b (HR b)
            end).
  split.
  - hnf; simpl.
    intros a a' b Ha Hab.
    destruct a as [a|[a q]]; simpl in *.
    + hnf in Ha. simpl in *.
      destruct a' as [a'|[a' q]].
      * unfold wf_ord_elt in *.
        rewrite Hab in Ha.
        destruct (HR b); simpl in *.
        rewrite ord_lt_unfold in Ha. simpl in Ha.
        destruct Ha as [[b' Hb'] Ha]. simpl in *.
        exists b'; split; auto.
        rewrite Ha.
        apply wf_ord_Acc_irrelevant; auto.
      * unfold wf_ord_elt in Ha.
        rewrite Hab in Ha.
        rewrite ord_lt_unfold in Ha.
        destruct (HR b); simpl in *.
        destruct Ha as [[b' Hb'] Ha]. simpl in *.
        exists b'; split; auto.
        rewrite Ha.
        apply wf_ord_Acc_irrelevant.
    + unfold ord_R in Ha. simpl in Ha.
      destruct a' as [a'|[a' q']].
      * simpl in *. rewrite Hab in Ha.
        rewrite ord_lt_unfold in Ha.
        destruct (HR b). simpl in *.
        destruct Ha as [[b' Hb'] Ha]. simpl in *.
        exists b'; split; auto.
        rewrite Ha.
        apply wf_ord_Acc_irrelevant.
      * rewrite Hab in Ha.
        destruct (HR b); simpl in *.
        rewrite ord_lt_unfold in Ha.
        destruct Ha as [[b' Hb'] Ha].
        simpl in *.
        exists b'. split; auto.
        rewrite Ha.
        apply wf_ord_Acc_irrelevant.
  - hnf; simpl.
    intros [i|[i q]]; eauto.
    exists i. auto with ord.
    destruct (HR i); simpl in *.
    destruct q as [[a' Ha']|[[a' Ha'] q']]; auto.
    + simpl.
      exists a'.
      apply wf_ord_Acc_irrelevant.
    + simpl in *.
      exists a'.
      transitivity (ord_transitive_closure (mk_wf_ord A R a' (a a' Ha'))).
      apply ord_lt_le. rewrite ord_lt_unfold; simpl. exists q'.
      auto with ord.
      rewrite ord_transitive_closure_eq.
      apply wf_ord_Acc_irrelevant.
Qed.
